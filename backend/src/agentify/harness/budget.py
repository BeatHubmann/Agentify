"""Cumulative error budget, counted in the harness loop (A§10.3).

The framework's own per-tool retry counter resets after a success (spike S1.2), so Agentify counts
every retry prompt the model receives, whether raised by a tool or generated by the framework
(argument validation, unknown tool), and aborts the run when any limit is exceeded.
"""

import json
from collections import Counter
from dataclasses import dataclass, field

from pydantic_ai.messages import ModelRequest, RetryPromptPart

FRAMEWORK_CLASS = "framework_validation"


class RunAbort(Exception):
    def __init__(self, reason: str, detail: str = "") -> None:
        super().__init__(f"{reason}: {detail}" if detail else reason)
        self.reason = reason
        self.detail = detail


def _error_class(part: RetryPromptPart) -> str:
    if isinstance(part.content, str):
        try:
            payload = json.loads(part.content)
        except ValueError:
            return FRAMEWORK_CLASS
        if isinstance(payload, dict) and isinstance(payload.get("error"), str):
            return str(payload["error"])
    return FRAMEWORK_CLASS


@dataclass
class ErrorBudget:
    per_tool: int
    per_class: int
    per_run: int
    tools: Counter[str] = field(default_factory=Counter)
    classes: Counter[str] = field(default_factory=Counter)
    total: int = 0

    def count(self, request: ModelRequest) -> None:
        for part in request.parts:
            if not isinstance(part, RetryPromptPart):
                continue
            tool = part.tool_name or "(output)"
            error_class = _error_class(part)
            self.tools[tool] += 1
            self.classes[error_class] += 1
            self.total += 1
        if (
            self.total > self.per_run
            or any(n > self.per_tool for n in self.tools.values())
            or any(n > self.per_class for n in self.classes.values())
        ):
            raise RunAbort("error_budget_exhausted", self.summary())

    def summary(self) -> str:
        return json.dumps(
            {"tools": dict(self.tools), "classes": dict(self.classes), "total": self.total},
            sort_keys=True,
        )
